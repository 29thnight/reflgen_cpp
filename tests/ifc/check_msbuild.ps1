param(
    [Parameter(Mandatory)][string]$Generator,
    [Parameter(Mandatory)][string]$MSBuild,
    [Parameter(Mandatory)][string]$Work,
    [ValidateSet('Debug', 'Release')][string]$Configuration = 'Debug'
)
$ErrorActionPreference = 'Stop'
$Work = [IO.Path]::GetFullPath($Work).TrimEnd('\', '/') + '\'
# Use a private fixture copy so incremental-source tests never edit repository files.
$fixture = Join-Path $Work 'fixture'
New-Item -ItemType Directory -Path $fixture -Force | Out-Null
Copy-Item -Path (Join-Path $PSScriptRoot '*') -Destination $fixture -Recurse -Force
# Copy-Item preserves source timestamps; force recompilation after resetting a previously edited fixture.
(Get-Item -LiteralPath (Join-Path $fixture 'types.ixx')).LastWriteTimeUtc = [DateTime]::UtcNow
$project = Join-Path $fixture 'msbuild/reflection.vcxproj'
[xml]$reflectionProject = Get-Content -LiteralPath $project -Raw
$targetsPath = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../../msbuild/reflgen.ifc.targets'))
foreach ($import in $reflectionProject.Project.Import) {
    if ($import.Project.EndsWith('reflgen.ifc.targets')) { $import.Project = $targetsPath }
}
$reflectionProject.Save($project)
$providerProject = Join-Path $fixture 'msbuild/provider.vcxproj'
[xml]$providerXml = Get-Content -LiteralPath $providerProject -Raw
foreach ($import in $providerXml.Project.Import) {
    if ($import.Project.EndsWith('reflgen.ifc.metadata.targets')) {
        $import.Project = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../../msbuild/reflgen.ifc.metadata.targets'))
    }
}
$providerXml.Save($providerProject)
# Prove attribute-only saves regenerate the schema without changing the semantic field list.
$moduleSource = Join-Path $fixture 'types.ixx'
$annotated = (Get-Content -LiteralPath $moduleSource -Raw).Replace('int health = 100;', '[[reflgen::serialized_name("hp")]] int health = 100;')
[IO.File]::WriteAllText($moduleSource, $annotated)
$arguments = @($project, '/nologo', '/v:minimal', "/p:Configuration=$Configuration", '/p:Platform=x64',
    "/p:ReflgenIfcExecutable=$Generator", "/p:IfcTestWork=$Work")
function Invoke-Build([string]$Target) {
    $log = & $MSBuild @arguments "/t:$Target" 2>&1
    if ($LASTEXITCODE -ne 0) { throw ($log -join "`n") }
    $log | Write-Output
}
Invoke-Build 'Build'
$executable = Join-Path $Work "$Configuration/bin/reflection.exe"
& $executable
if ($LASTEXITCODE -ne 0) { throw 'MSBuild IFC runtime failed' }
$output = Join-Path $Work "$Configuration/obj/reflection/reflgen-ifc"
$header = Join-Path $output 'reflgen_ifc_game.h'
$source = Join-Path $output 'reflgen_ifc_game.cpp'
$stamp = Join-Path $output 'reflgen_ifc_game.stamp'
$headerTime = (Get-Item -LiteralPath $header).LastWriteTimeUtc
$stampTime = (Get-Item -LiteralPath $stamp).LastWriteTimeUtc
if ((Get-Content -LiteralPath $header -Raw) -notmatch 'serialized_name\("hp"\)') { throw 'MSBuild lost module attributes' }
Invoke-Build 'ReflgenGenerate'
if ((Get-Item -LiteralPath $header).LastWriteTimeUtc -ne $headerTime -or
    (Get-Item -LiteralPath $stamp).LastWriteTimeUtc -ne $stampTime) { throw 'No-op generation rewrote output' }
# Delete only this test's known generated byproduct, then exercise the VS save target.
Remove-Item -LiteralPath $source
Invoke-Build 'ReflgenGenerate'
if (!(Test-Path -LiteralPath $source)) { throw 'Missing generated source was not recovered' }
if ((Get-Item -LiteralPath $header).LastWriteTimeUtc -ne $headerTime) { throw 'Recovery rewrote unchanged header' }
$moduleSource = Join-Path $fixture 'types.ixx'
$changed = (Get-Content -LiteralPath $moduleSource -Raw).Replace('int health = 100;', 'int health = 100; int experience = 3;')
[IO.File]::WriteAllText($moduleSource, $changed)
Invoke-Build 'ReflgenGenerate'
if ((Get-Content -LiteralPath $header -Raw) -notmatch 'T::experience') { throw 'Module save used a stale IFC' }
$changed = (Get-Content -LiteralPath $moduleSource -Raw).Replace('serialized_name("hp")', 'serialized_name("health_points")')
[IO.File]::WriteAllText($moduleSource, $changed)
Invoke-Build 'Build'
if ((Get-Content -LiteralPath $header -Raw) -notmatch 'serialized_name\("health_points"\)') { throw 'Attribute-only save used stale metadata' }
$corrupt = Join-Path $output 'corrupt.ifc'
$image = [IO.File]::ReadAllBytes((Join-Path $Work "$Configuration/bin/types.ifc"))
$image[4] = $image[4] -bxor 1
[IO.File]::WriteAllBytes($corrupt, $image)
$failure = & $Generator --ifc $corrupt --import reflgen.test.types --module corrupt --output $output 2>&1
if ($LASTEXITCODE -eq 0 -or ($failure -join '') -notmatch 'integrity check failed') { throw 'Corrupt IFC was accepted' }
Write-Output "IFC_MSBUILD_OK $Configuration : runtime, no-op, missing-output recovery, fresh IFC after module edit, integrity rejection"
